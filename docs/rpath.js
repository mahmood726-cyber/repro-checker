/* reprocheck — R path: "Download R script" + in-page "Verify in R" (WebR).
 *
 * Both run ONE script, generated from the submission currently in the text box
 * and the numbers the page just computed (RC.check). The script re-pools the
 * same study table with metafor (the reference named in the validation archive,
 * PREREG section 3: escalc add=1/2 to="only0"; rma REML z-test; t_{k-1}
 * prediction interval) and prints, per number: page value, R value, difference,
 * tolerance and ok/DIFF, then one final line "MATCH n/n" or "MISMATCH m/n".
 * Tolerances are the pre-registered ones: |page - R| <= tol * max(1, |R|),
 * tol 1e-9 for closed-form quantities (Q, I2), 1e-7 for REML-dependent ones;
 * k exact. If the page did not recompute (unsupported measure, no data, ...)
 * no script is run and the result is "NOT CHECKED" with the page's reason.
 */
(function (global) {
  "use strict";
  var WEBR_BASE = "https://webr.r-wasm.org/v0.5.4/";   // pinned (as allmeta's pages)

  function rnum(x) {
    if (x === null || x === undefined || typeof x !== "number" || isNaN(x)) return "NA";
    if (x === Infinity) return "Inf";
    if (x === -Infinity) return "-Inf";
    return String(x);                       // shortest round-trip form: the exact double
  }
  function rstr(s) { return '"' + String(s == null ? "" : s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/[\r\n]/g, " ") + '"'; }
  function vec(a, f) { return "c(" + a.map(f).join(", ") + ")"; }

  function shapeOf(t) {
    if (t.tE != null && t.tN != null && t.cE != null && t.cN != null) return "count";
    if (t.effect != null && t.elci != null && t.euci != null) return "effect";
    return null;
  }

  // Returns {ok:true, script} or {ok:false, reason} (NOT CHECKED).
  function buildScript(sub, rep) {
    if (!rep || !rep.recomputed) {
      var cv = (rep && rep.claims || []).filter(function (c) { return c.quantity.indexOf("pooled") === 0; })[0];
      return { ok: false, reason: "the page did not re-pool this submission" + (cv && cv.reason ? " (" + cv.reason + ")" : "") };
    }
    var p = rep.recomputed;
    var measure = rep.measure === "RR" ? "RR" : "OR";     // what RC.check pooled counts as
    var rows = (sub.trials || []).filter(function (t) { return shapeOf(t) != null; });
    var L = [];
    L.push("# reprocheck - R re-check of the page's pooled numbers (metafor)");
    L.push("# Generated by the reprocheck page from the submission in its text box.");
    L.push("# Reference: metafor escalc(add=1/2, to='only0', drop00=FALSE); rma(method='REML', test='z');");
    L.push("# I2 = max(0,(Q-df)/Q); prediction interval exp(mu +/- qt(.975,k-1)*sqrt(tau2+se^2)).");
    L.push("# Tolerance (pre-registered, PREREG s3): |page-R| <= tol*max(1,|R|); tol 1e-9 for Q and I2,");
    L.push("# 1e-7 for REML-dependent numbers; k exact.");
    L.push("suppressPackageStartupMessages(library(metafor))");
    L.push("measure <- " + rstr(measure) + "   # count rows are pooled as this measure");
    L.push("dat <- data.frame(");
    L.push("  name   = " + vec(rows, function (t) { return rstr(t.name); }) + ",");
    L.push("  shape  = " + vec(rows, function (t) { return rstr(shapeOf(t)); }) + ",");
    ["tE", "tN", "cE", "cN", "effect", "elci", "euci"].forEach(function (f, i, arr) {
      L.push("  " + (f + "      ").slice(0, 6) + " = " + vec(rows, function (t) { return shapeOf(t) === (i < 4 ? "count" : "effect") ? rnum(t[f]) : "NA"; }) + ",");
    });
    L.push("  stringsAsFactors = FALSE)");
    L.push("page <- c(est = " + rnum(p.est) + ", lci = " + rnum(p.lci) + ", uci = " + rnum(p.uci) + ",");
    L.push("          tau2 = " + rnum(p.tau2) + ", Q = " + rnum(p.Q) + ", I2 = " + rnum(p.I2) + ",");
    L.push("          pi_lci = " + rnum(p.pi_lci) + ", pi_uci = " + rnum(p.pi_uci) + ", k = " + rnum(p.k) + ")");
    L.push("");
    L.push("yi <- numeric(nrow(dat)); vi <- numeric(nrow(dat))");
    L.push("for (i in seq_len(nrow(dat))) {");
    L.push("  if (dat$shape[i] == 'effect') {");
    L.push("    yi[i] <- log(dat$effect[i])");
    L.push("    vi[i] <- ((log(dat$euci[i]) - log(dat$elci[i])) / (2 * qnorm(0.975)))^2");
    L.push("  } else {");
    L.push("    es <- escalc(measure = measure, ai = dat$tE[i], n1i = dat$tN[i], ci = dat$cE[i], n2i = dat$cN[i],");
    L.push("                 add = 1/2, to = 'only0', drop00 = FALSE)");
    L.push("    yi[i] <- as.numeric(es$yi); vi[i] <- as.numeric(es$vi)");
    L.push("  }");
    L.push("}");
    L.push("k <- length(yi)");
    L.push("if (k == 1) {   # one study: no heterogeneity, no prediction interval");
    L.push("  mu <- yi[1]; se <- sqrt(vi[1]); tau2 <- 0; Q <- 0; I2 <- 0; pil <- NA; piu <- NA");
    L.push("} else {");
    L.push("  fit <- rma(yi, vi, method = 'REML', test = 'z', control = list(threshold = 1e-15, maxiter = 100000))");
    L.push("  mu <- as.numeric(fit$beta); se <- fit$se; tau2 <- fit$tau2; Q <- fit$QE");
    L.push("  I2 <- if (Q > 0) max(0, (Q - (k - 1)) / Q) * 100 else 0");
    L.push("  half <- qt(0.975, k - 1) * sqrt(tau2 + se^2); pil <- exp(mu - half); piu <- exp(mu + half)");
    L.push("}");
    L.push("z <- qnorm(0.975)");
    L.push("R <- c(est = exp(mu), lci = exp(mu - z * se), uci = exp(mu + z * se), tau2 = tau2, Q = Q, I2 = I2,");
    L.push("       pi_lci = pil, pi_uci = piu, k = k)");
    L.push("tol <- c(est = 1e-7, lci = 1e-7, uci = 1e-7, tau2 = 1e-7, Q = 1e-9, I2 = 1e-9,");
    L.push("         pi_lci = 1e-7, pi_uci = 1e-7, k = 0)");
    L.push("cat(sprintf('%-8s %22s %22s %11s %8s  %s\\n', 'number', 'page', 'R (metafor)', 'diff', 'tol', 'result'))");
    L.push("ok <- logical(0)");
    L.push("for (q in names(R)) {");
    L.push("  a <- page[[q]]; r <- R[[q]]");
    L.push("  if (is.na(a) && is.na(r)) { good <- TRUE; d <- NA }      # both undefined (k = 1 PI)");
    L.push("  else if (is.na(a) || is.na(r)) { good <- FALSE; d <- NA }");
    L.push("  else { d <- a - r; good <- abs(d) <= tol[[q]] * max(1, abs(r)) }");
    L.push("  ok[q] <- good");
    L.push("  cat(sprintf('%-8s %22.15g %22.15g %11.3g %8.0e  %s\\n', q, a, r, d, tol[[q]], if (good) 'ok' else 'DIFF'))");
    L.push("}");
    L.push("cat(sprintf('metafor %s, %s\\n', as.character(packageVersion('metafor')), R.version.string))");
    L.push("if (all(ok)) cat(sprintf('MATCH %d/%d\\n', sum(ok), length(ok))) else");
    L.push("  cat(sprintf('MISMATCH %d/%d differ: %s\\n', sum(!ok), length(ok), paste(names(ok)[!ok], collapse = ', ')))");
    return { ok: true, script: L.join("\n") + "\n" };
  }

  function download(text, filename) {
    var blob = new Blob([text], { type: "text/x-r;charset=utf-8" });
    var url = URL.createObjectURL(blob), a = document.createElement("a");
    a.href = url; a.download = filename;
    document.body.appendChild(a); a.click();
    setTimeout(function () { document.body.removeChild(a); URL.revokeObjectURL(url); }, 0);
  }

  // ---- WebR ---------------------------------------------------------------
  var _boot = null, _pk = {};
  function webR(onStatus) {
    if (_boot) return _boot;
    onStatus("Loading WebR " + WEBR_BASE + " (one-time, ~30 MB)...");
    _boot = import(WEBR_BASE + "webr.mjs").then(function (mod) {
      var w = new mod.WebR({ baseUrl: WEBR_BASE, interactive: false });
      return w.init().then(function () { return w; });
    });
    _boot.catch(function () { _boot = null; });
    return _boot;
  }
  function ensurePkgs(w, pkgs, onStatus) {
    var todo = pkgs.filter(function (p) { return !_pk[p]; });
    if (!todo.length) return Promise.resolve();
    onStatus("Installing R package(s) in WebR: " + todo.join(", ") + "...");
    return w.installPackages(todo, { quiet: true }).then(function () {
      // installPackages does not throw when a package is missing from the WebR repo: check.
      return w.evalRString("paste(Filter(function(p) !requireNamespace(p, quietly=TRUE), c(" +
        todo.map(function (p) { return '"' + p + '"'; }).join(",") + ")), collapse=', ')");
    }).then(function (missing) {
      if (missing) throw new Error("R package not available in WebR: " + missing);
      todo.forEach(function (p) { _pk[p] = 1; });
    });
  }
  // Resolves {status:"MATCH"|"MISMATCH"|"NOT CHECKED", line, output}
  function runInWebR(script, pkgs, onStatus) {
    var w0;
    return webR(onStatus).then(function (w) { w0 = w; return ensurePkgs(w, pkgs, onStatus); })
      .then(function () {
        onStatus("Running the R script in WebR...");
        return new w0.Shelter();
      }).then(function (sh) {
        return sh.captureR(script, { captureStreams: true, withAutoprint: false }).then(function (cap) {
          sh.purge();
          var out = (cap.output || []).map(function (c) { return (c.type === "stderr" ? "! " : "") + c.data; }).join("\n");
          var lines = out.split("\n").filter(function (s) { return /^(MATCH|MISMATCH) /.test(s); });
          var line = lines.length ? lines[lines.length - 1] : "";
          var status = /^MATCH /.test(line) ? "MATCH" : /^MISMATCH /.test(line) ? "MISMATCH" : "NOT CHECKED";
          if (status === "NOT CHECKED") line = "NOT CHECKED: the R script printed no MATCH/MISMATCH line";
          return { status: status, line: line, output: out };
        }, function (e) { sh.purge(); throw e; });
      }).catch(function (e) {
        return { status: "NOT CHECKED", line: "NOT CHECKED: " + (e && e.message || e), output: "" };
      });
  }

  global.RCR = { buildScript: buildScript, download: download, runInWebR: runInWebR, WEBR_BASE: WEBR_BASE };
  if (typeof module !== "undefined" && module.exports) module.exports = global.RCR;
})(typeof window !== "undefined" ? window : globalThis);
